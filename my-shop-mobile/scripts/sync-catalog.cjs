// Copy the web catalog without coupling mobile runtime code to Next.js.
const fs = require("node:fs");
const path = require("node:path");
const prettier = require("prettier");
const root = path.resolve(__dirname, "..");
const web = path.resolve(root, "../my-shop-front-end");
const config = JSON.parse(
  fs.readFileSync(path.join(root, ".prettierrc"), "utf8")
);
function list(dir) {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) =>
      entry.isDirectory()
        ? list(path.join(dir, entry.name))
        : [path.join(dir, entry.name)]
    );
}
async function writeTypeScript(file, content) {
  fs.writeFileSync(
    path.join(root, file),
    await prettier.format(content, { ...config, parser: "typescript" })
  );
}
async function syncCatalog() {
  for (const dir of ["src/data", "src/types", "assets/images"])
    fs.mkdirSync(path.join(root, dir), { recursive: true });
  await writeTypeScript(
    "src/types/product.ts",
    fs.readFileSync(path.join(web, "src/types/product.type.ts"), "utf8")
  );
  const products = fs
    .readFileSync(path.join(web, "src/lib/mockData.ts"), "utf8")
    .replace("@/types/product.type", "../types/product")
    .replace("import { Product }", "import type { Product }");
  await writeTypeScript("src/data/products.ts", products);
  fs.cpSync(path.join(web, "public/images"), path.join(root, "assets/images"), {
    recursive: true,
  });
  const files = list(path.join(root, "assets/images"));
  const entries = files.map((file) => {
    const relative = path
      .relative(path.join(root, "assets"), file)
      .replaceAll("\\", "/");
    return (
      JSON.stringify("/" + relative) +
      ": require(" +
      JSON.stringify("../../assets/" + relative) +
      "),"
    );
  });
  const remoteManifest = path.join(root, "assets/remote-images.json");
  if (fs.existsSync(remoteManifest))
    for (const { url, local } of JSON.parse(
      fs.readFileSync(remoteManifest, "utf8")
    ))
      entries.push(
        JSON.stringify(url) +
          ": require(" +
          JSON.stringify("../../assets" + local) +
          "),"
      );
  await writeTypeScript(
    "src/data/images.ts",
    '// Generated by scripts/sync-catalog.cjs. Metro requires static image paths.\nimport type { ImageSourcePropType } from "react-native";\nconst images: Record<string, ImageSourcePropType> = {\n' +
      entries.join("\n") +
      "\n};\nexport function imageSource(path: string): ImageSourcePropType { return images[path] ?? { uri: path }; }\n"
  );
  console.log("Synced catalog and " + files.length + " bundled images.");
}
module.exports = syncCatalog;
if (require.main === module)
  syncCatalog().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
